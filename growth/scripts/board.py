"""
board.py — render the whole growth board as one markdown document.

This is the artifact the company reads. It is generated, never hand-edited, because a
hand-edited board drifts from the data within two weeks and then nobody trusts it.

Emits, in order:
  0. the target verdict — can cadence reach 1M, and if not, what has to
  1. the follower-velocity chain
  2. the format scoreboard
  3. the topic scoreboard
  4. the channel scoreboard
  5. the noise floor
  6. the weekly per-agent targets
  7. the honest read, generated from the numbers rather than authored

Usage:
    python scripts/board.py                 # print markdown to stdout
    python scripts/board.py --out FILE      # write to FILE
"""

from __future__ import annotations

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import cadence_plan  # noqa: E402
import kill_gate  # noqa: E402
import noise_floor  # noqa: E402
import scoreboard  # noqa: E402
import target_model  # noqa: E402
import velocity_model  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
WINDOW = "24h"


def table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_no rows yet_\n"
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out) + "\n"


def fmt(value, digits=0, dash="-"):
    try:
        return f"{float(value):,.{digits}f}"
    except (TypeError, ValueError):
        return dash


def pct(value, digits=4, dash="-"):
    try:
        return f"{float(value) * 100:.{digits}f}%"
    except (TypeError, ValueError):
        return dash


def _wrap(text: str, width: int) -> list[str]:
    words, out, line = text.split(), [], ""
    for w in words:
        if len(line) + len(w) + 1 > width:
            out.append(line)
            line = w
        else:
            line = f"{line} {w}".strip()
    if line:
        out.append(line)
    return out


def group_table(rows: list[dict], key: str) -> str:
    headers = [
        key, "posts", "med impr", "p25", "p75", "max",
        "med eng", "med conv", "vs co", "kill_eligible",
    ]
    body = []
    for r in rows:
        body.append([
            r.get(key, ""),
            r.get("posts_shipped", 0) or 0,
            fmt(r.get(f"median_impressions_{WINDOW}")),
            fmt(r.get(f"p25_impressions_{WINDOW}")),
            fmt(r.get(f"p75_impressions_{WINDOW}")),
            fmt(r.get(f"max_impressions_{WINDOW}")),
            pct(r.get(f"median_engagement_rate_{WINDOW}"), 2),
            pct(r.get(f"median_follower_conversion_{WINDOW}"), 4),
            r.get(f"vs_company_median_{WINDOW}") or "-",
            (r.get("kill_eligible") or "-").replace("|", "/"),
        ])
    return table(headers, body)


def main() -> None:
    model = velocity_model.build()
    floor = noise_floor.build()
    posts = scoreboard.read_csv(DATA / "posts.csv")
    mature = scoreboard.mature(posts, WINDOW)
    formats = scoreboard.group_scoreboard(mature, "format", scoreboard.FORMATS, WINDOW)
    topics = scoreboard.group_scoreboard(mature, "topic", scoreboard.TOPICS, WINDOW)

    gate = {r["format"]: r["kill_eligible"] for r in kill_gate.evaluate(DATA / "format_scoreboard.csv", "format")}
    topic_gate = {r["topic"]: r["kill_eligible"] for r in kill_gate.evaluate(DATA / "topic_scoreboard.csv", "topic")}
    for row in formats:
        row["kill_eligible"] = gate.get(row["format"], "-")
    for row in topics:
        row["kill_eligible"] = topic_gate.get(row["topic"], "-")

    channels = scoreboard.read_csv(DATA / "channel_scoreboard.csv")
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    tmodel = target_model.build()
    reach = tmodel["reachability"]
    plan = cadence_plan.build()

    print(f"# Growth board — {today}\n")
    print(f"_Generated by `growth/scripts/board.py` at "
          f"{datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}. "
          f"Do not hand-edit; fix the data or the code. Data state: **{model['data_state']}**._\n")

    print("## 0. The verdict, before the numbers\n")
    for chunk in _wrap(reach["verdict"], 90):
        print(chunk)
    print("")
    print(table(
        ["scenario", "day-90 followers", "% of target"],
        [[name, fmt(s["day_90_followers"]), f"{s['pct_of_target']:.3f}%"]
         for name, s in sorted(tmodel["scenarios"].items())],
    ))
    print(f"Cadence alone reaches the target: "
          f"**{'YES' if reach['cadence_can_reach_target_alone'] else 'NO'}**\n")

    slip = tmodel["slip_impact"]
    if not slip["account_exists"]:
        print(f"**The account does not exist.** {slip['note']}\n")
        print(table(
            ["start delay", "runway (days)", "required/day", "required/week"],
            [[f"+{r['start_delay_days']}d", r["runway_days"], fmt(r["required_per_day"]),
              fmt(r["required_per_week"])] for r in slip["table"]],
        ))

    print("## 1. Follower velocity\n")
    print("```")
    print("current_followers  = " + (fmt(model["current_followers"]) if model["current_followers"] is not None else "n/a"))
    print("net_new_7d         = " + (fmt(model["net_new_7d"]) if model["net_new_7d"] is not None else "n/a"))
    print("velocity_per_day   = " + (fmt(model["velocity_per_day"], 2) if model["velocity_per_day"] is not None else "n/a"))
    print(f"velocity 95% CI    = {model['velocity_95ci'] or 'n/a'}")
    print("projected_day_90   = " + fmt(model["projected_day_90"]))
    print("gap_to_target      = " + fmt(model["gap_to_target"]) + f"  ({model['gap_to_target_pct']}% of target)")
    print("run_rate_vs_target = " + pct(model["run_rate_vs_target"], 3))
    print("```\n")
    print(f"Required to hit 1,000,000 in 90 days: **{fmt(model['required_velocity_per_day'], 0)} net new/day.**\n")
    print(f"**Honest read.** {model['honest_read']}\n")
    if model["velocity_95ci"] and model["net_new_7d"] is not None:
        low, high = model["velocity_95ci"]
        if high - low > max(model["velocity_per_day"], 1) * 2:
            print(f"> The 95% interval on velocity ({low} to {high}/day) is wider than the point "
                  f"estimate. This week's velocity is not yet a velocity.\n")

    print("## 2. Format scoreboard (T+24h, medians)\n")
    print(group_table(formats, "format"))

    print("\n## 3. Topic scoreboard (T+24h, medians)\n")
    print(group_table(topics, "topic"))

    print("\n## 4. Channel scoreboard (48h attribution)\n")
    if channels:
        rows = [[
            c.get("channel", ""), c.get("platform", ""), c.get("shipped_at_utc", ""),
            fmt(c.get("net_new_followers_48h")), fmt(c.get("impressions_48h")),
            pct(c.get("conversion_48h"), 4), c.get("verdict", "-") or "-",
        ] for c in channels]
        print(table(["channel", "platform", "shipped", "net new 48h", "impr 48h", "conv", "verdict"], rows))
    else:
        print("_No off-platform touches logged. Schema is fixed in "
              "`data/channel_scoreboard.csv`; rows append on the first push._\n")

    print("\n## 5. Noise floor\n")
    print(f"- State: **{floor['state']}**, {floor['mature_posts']} mature posts\n"
          f"- Overdispersion phi: **{floor['overdispersion_alpha']}** "
          f"(sample-size multiplier {floor['sample_size_multiplier']}x)\n"
          f"- {floor['overdispersion_provenance']}\n"
          f"- Kill floor, 2x gap: **{fmt(floor['kill_floor_impressions_per_arm_2x'])} impressions per arm**\n")
    for row in floor["table"]:
        cell = row["by_ratio"]["2.0"]
        print(f"  - At a {pct(row['assumed_baseline_conversion'], 3)} conversion rate, a 2x gap needs "
              f"{fmt(cell['impressions_per_arm_adjusted'])} impressions per arm, about "
              f"{cell['posts_per_arm_at_5000_median_impressions']} posts at a 5,000 median.\n")
    print(f"\n**Honest read.** {floor['honest_read']}\n")

    print("## 6. Weekly per-agent targets\n")
    print(f"The growth line: **{fmt(plan['follower_line']['company_weekly_target'])} followers/week**, "
          f"95% interval {fmt(plan['follower_line']['company_weekly_ci95'][0])} to "
          f"{fmt(plan['follower_line']['company_weekly_ci95'][1])} "
          f"(+-{plan['follower_line']['relative_half_width'] * 100:.0f}%).\n")
    print(f"> {plan['follower_line']['per_agent_follower_targets']}\n")
    print(table(
        ["agent", "lever", "weekly target", "unit"],
        [[a["agent"], a["lever"], a["target"], a["unit"]] for a in plan["agent_targets"]],
    ))
    print(f"_{plan['measurability_rule']['formula']}. Below n={plan['measurability_rule']['min_n_for_30pct']} "
          f"an outcome rate is noise. The counts above are process counts and are exact; the noise "
          f"lives in the outcomes they produce._\n")

    print("---\n")
    print("_Read `how-to-read` on this issue for the column definitions, the diagnostics "
          "order, and what each week is and is not allowed to conclude._")


if __name__ == "__main__":
    if "--out" in sys.argv:
        target = Path(sys.argv[sys.argv.index("--out") + 1])
        import io, contextlib
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            main()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(buffer.getvalue(), encoding="utf-8")
        print(f"wrote {target}")
    else:
        main()
